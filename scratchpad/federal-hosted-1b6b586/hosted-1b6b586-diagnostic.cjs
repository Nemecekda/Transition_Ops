const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = fs.readFileSync('netlify/functions/resume.mjs', 'utf8');
const names = ['factRoles', 'explicitLaterRoleTitles', 'roleDutyAtomRecords', 'globalExactItemRecords', 'factSheetIssues', 'hasExactBoundaryOccurrence', 'exactQuantityTokens', 'factCatalog', 'draftEligibleFacts'];
const functions = names.map(name => {
  const matches = Array.from(source.matchAll(new RegExp('^  function ' + name + '\\([^\\n]*\\) \\{[\\s\\S]*?^  \\}', 'gm')));
  assert.equal(matches.length, 1, 'Actual function boundary: ' + name);
  return matches[0][0];
}).join('\n');
const specs = source.match(/  const GLOBAL_EXACT_ITEM_SPECS = \[[\s\S]*?\n  \];/g);
assert.equal(specs.length, 1);
const context = {};
vm.runInNewContext(specs[0] + '\n' + functions, context);
const memberSource = 'Operations Lead at North Test Depot, January 2023 - December 2025. Reviewed equipment records for 12 teams.';
const factSheet = 'ROLE 1\nJOB TITLE (EXACT): Operations Lead\nEMPLOYER OR UNIT (EXACT): North Test Depot\nLOCATION (EXACT OR MISSING): MISSING\nDATES (EXACT OR MISSING): January 2023 - December 2025\nDUTIES AND OUTCOMES (EXACT FACTS ONLY):\nDUTY ATOM 1 (EXACT): Reviewed equipment records for 12 teams.\n\nEDUCATION (EXACT OR MISSING): MISSING\nCERTIFICATIONS (EXACT OR MISSING): MISSING\nSKILLS AND TOOLS (EXACT OR MISSING): equipment records\nNUMBERS AND SCALE (EXACT OR MISSING):\n12 teams\n26 years of service\nTARGET ROLE (EXACT OR MISSING): Program Analyst';
assert.equal(memberSource.includes('26'), false);
assert.equal(context.factSheetIssues(factSheet, memberSource).length, 0);
const catalog = context.factCatalog(factSheet);
const falseTenure = catalog.find(fact => fact.text === '26 years of service');
assert.ok(falseTenure);
assert.equal(falseTenure.owner, 'global');
assert.equal(falseTenure.unlinked_number, false);
const eligible = context.draftEligibleFacts(catalog, 'federal');
assert.ok(eligible.some(fact => fact.text === '26 years of service'));
assert.equal(context.exactQuantityTokens(memberSource).includes('26'), false);
assert.equal(context.exactQuantityTokens('Reference year 2026.').includes('26'), false);
console.log('REPRODUCED: unsupported 26 years passes factSheetIssues with zero warnings.');
console.log('REPRODUCED: multiline NUMBERS continuation is cataloged global/unlinked_number=false and reaches federal draft-eligible facts.');
console.log('CONFIRMED: existing exactQuantityTokens distinguishes 26 from 2026; a source-presence gate can detect this absent value.');
console.log('SCOPE: extracted actual functions, fictional fixture, zero provider calls; this diagnoses failure, not acceptance.');
